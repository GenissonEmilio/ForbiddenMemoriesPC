#!/usr/bin/env python3
"""Links the browser build (after build.py and gen_data_web.py), like port/tools/link.py: a first pass asks the
linker what nobody provides, a stub is generated for each (it prints its name and stops), then the real link.

    port/web/link.py node     a Node.js program with the host's files (NODERAWFS): headless tests
    port/web/link.py web      the browser program (JSPI) -> port/build/web/
    port/web/link.py webasync the browser program (Asyncify, for Safari) -> port/build/web/

Memory: the game keeps PS2 addresses (plat_mem.c): its heap at 0x003BE000..0x02000000 and the hardware registers
at 0x10000000 and 0x12000000. WebAssembly memory starts at 0, so those addresses are simply kept free: the
program's own data, stack and C heap start above them (GLOBAL_BASE)."""
import shutil, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OBJ = ROOT / "port/build/obj_web"
OUT = ROOT / "port/build/web"
GLOBAL_BASE = 0x12100000

COMMON = [f"-sGLOBAL_BASE={GLOBAL_BASE}", "-sSTACK_SIZE=16MB", "-sINITIAL_MEMORY=640MB", "-sALLOW_MEMORY_GROWTH=1",
          "-sMAXIMUM_MEMORY=2048MB", "--use-port=sdl3", "-O3", "-sEXIT_RUNTIME=1", "--profiling-funcs", "-sEMULATE_FUNCTION_POINTER_CASTS=1",
          "-Wl,--wrap=Progress_Main"]  # as the native link: the game's mode dispatcher goes through headless.c
WEB = ROOT / "port/web"
WEB_COMMON = ["-sENVIRONMENT=web", "-sMAX_WEBGL_VERSION=2", "-sMIN_WEBGL_VERSION=2", "-lidbfs.js",
              "-sFORCE_FILESYSTEM=1", "-sINVOKE_RUN=0", "-sEXPORTED_RUNTIME_METHODS=callMain,FS,ENV,IDBFS",
              f"--pre-js={WEB / 'web_pre.js'}"]
TARGETS = {
    "node": ["-sASSERTIONS=1", "-sSTACK_OVERFLOW_CHECK=1", "-sENVIRONMENT=node", "-sNODERAWFS=1", f"--pre-js={WEB / 'node_pre.js'}"],
    # The program suspends at its waits and file reads (target/yield_web.c, target/disc_web.c). Two builds of the
    # same program, the page picks one (shell.html): JSPI where the browser has it (Chrome, Edge), else Asyncify
    # (Safari, iPhone: the compiler rewrites the functions that can be on the stack at a wait so they can unwind).
    "web": WEB_COMMON + ["-sJSPI=1"],
    "webasync": WEB_COMMON + ["-sASYNCIFY=1", "-sASYNCIFY_STACK_SIZE=1MB"],
}
OUTNAME = {"node": "bt3_node.js", "web": "bt3-jspi.js", "webasync": "bt3-async.js"}
# per-target C files: the waits and the file opens (node: plain; web: suspending, from the disc image)
TARGET_SRC = {"node": ["yield_node.c", "disc_node.c"], "web": ["yield_web.c", "disc_web.c", "gl_web.c"]}
TARGET_SRC["webasync"] = TARGET_SRC["web"]


def link(target, objs, extra):
    OUT.mkdir(parents=True, exist_ok=True)
    out = OUT / OUTNAME[target]
    cmd = ["emcc"] + objs + extra + COMMON + TARGETS[target] + ["-o", str(out)]
    return subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT), out


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "node"
    if target not in TARGETS:
        print(f"Unknown target {target!r}; choose node, web or webasync", file=sys.stderr)
        return 2
    missing = [name for name in ("objects.txt", "data_objects.txt") if not (OBJ / name).is_file()]
    if missing:
        print("Missing " + ", ".join(missing) + "; run python3 port/web/build.py first "
              "(after extracting your own BT3 USA disc).", file=sys.stderr)
        return 2
    objs = (OBJ / "objects.txt").read_text().split() + (OBJ / "data_objects.txt").read_text().split()
    for f in TARGET_SRC[target]:
        o = OBJ / f"target_{f[:-2]}.o"
        subprocess.run(["emcc", "-c", "-O2", "-w", f"-I{WEB / 'include'}", str(WEB / "target" / f), "-o", str(o)], check=True)
        objs.append(str(o))
    r, _ = link(target, objs, ["-sERROR_ON_UNDEFINED_SYMBOLS=0", "-sWARN_ON_UNDEFINED_SYMBOLS=1"])
    need = sorted(set(re.findall(r"undefined symbol: (\w+)", r.stderr)))
    lines = ["/* Generated by port/web/link.py: one stub per symbol the browser build does not provide yet. */",
             "extern int printf(const char *, ...);", "extern void exit(int);",
             'static void missing(const char *n) { printf("bt3: not implemented yet: %s\\n", n); exit(3); }']
    lines += [f'void {s}(void) {{ missing("{s}"); }}' for s in need]
    stubs = OBJ / "stubs.c"
    stubs.write_text("\n".join(lines) + "\n")
    (OBJ / "stubs.txt").write_text("\n".join(need) + "\n")
    so = OBJ / "stubs.o"
    subprocess.run(["emcc", "-c", "-O2", str(stubs), "-o", str(so)], check=True)
    r, out = link(target, objs + [str(so)], [])
    if target != "node":
        (OUT / "index.html").write_text((WEB / "shell.html").read_text())
        for f in ("net.js", "net.css"):  # online play's screens and connection (Dragon Net Battle)
            shutil.copy(WEB / f, OUT / f)
        subprocess.run([sys.executable, str(WEB / "make_icons.py")], check=True)
    errs = [l for l in r.stderr.splitlines() if "error" in l or "mismatch" in l]
    print(f"{len(need)} stubs; link {'OK -> ' + str(out.relative_to(ROOT)) if r.returncode == 0 else 'FAILED'}")
    for l in errs[:20]:
        print("  " + l[:220])
    return r.returncode


if __name__ == "__main__":
    sys.exit(main())
